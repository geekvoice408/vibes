#if os(macOS)
import AppKit
import SwiftUI
import EeroCore

/// A saved conversation in the history picker (port of `HistoryItem`).
struct HistoryItem: Identifiable, Hashable {
    let id: String
    let label: String
}

/// One element in the chat transcript.
struct ChatEntry: Identifiable {
    enum Kind {
        case bubble(sender: String, text: String)
        /// A suggested prompt or widget choice that fills the input and sends it.
        case prompt(label: String, prompt: String)
        case feedback(messageId: String)
        case permission(id: String, permission: JSON)
        case widget(JSON, active: Bool)
    }
    let id = UUID()
    var kind: Kind
}

/// Cancellation source for one streamed reply (stop button, permission request, 3-minute limit, window close).
@MainActor
private final class StreamSource {
    private(set) var cancelled = false
    var task: Task<Void, Error>?
    func cancel() { cancelled = true; task?.cancel() }
}

/// Chat with eero (port of `ConversationWindow`).
@MainActor
final class ConversationController: ObservableObject {
    static let widgetFields = ["name", "location", "model", "status", "connected", "connection_type", "connection_state", "device_type", "is_guest", "is_private", "score_bars", "mesh_quality_bars", "wan_type", "eero", "port_number", "negotiated_speed", "total_devices", "paused_devices", "accessory_type", "bars", "cellular_backup_status", "configuration_status"]

    let api: EeroAPI?
    let networkId: String
    let networkName: String
    let sample: Bool
    let showHistory: Bool
    weak var window: NSWindow?

    @Published var entries: [ChatEntry] = []
    @Published var input = ""
    @Published var status = "Your chat is sent to eero. Review any requested network changes before approving."
    @Published private(set) var running = false
    @Published private(set) var stopEnabled = false
    @Published var history: [HistoryItem] = []
    @Published var selectedHistory: String?
    @Published private(set) var answered: Set<String> = []
    /// Bumped whenever the transcript should scroll to its end.
    @Published private(set) var scrollTick = 0

    private var deltas: [String: UUID] = [:]
    private var rendered: Set<String> = []
    private var feedback: Set<String> = []
    private var widgets: [String: UUID] = [:]
    private var cancellation: StreamSource?
    private var conversationId: String?
    private var mcpToken: String?
    private var closed = false
    private var waitingForPermission = false
    private var started = false

    init(api: EeroAPI?, networkId: String, networkName: String, sample: Bool, showHistory: Bool) {
        self.api = api; self.networkId = networkId; self.networkName = networkName; self.sample = sample; self.showHistory = showHistory
    }

    var subtitle: String { networkName + (sample ? " · Sample conversation" : " · Replies are generated by eero's assistant") }

    // MARK: Lifecycle

    /// Port of the `Loaded` handler.
    func start() {
        if started { return }
        started = true
        if sample { preview(); return }
        perform { try await self.loadHistory(); if !self.showHistory { try await self.recommendations() } }
    }

    /// Port of the `Closed` handler.
    func didClose() {
        closed = true
        cancellation?.cancel()
        mcpToken = nil; conversationId = nil
        deltas = [:]; entries = []; input = ""
    }

    // MARK: Actions

    /// Runs one action at a time with the controls disabled (port of `Perform`).
    func perform(_ action: @escaping @MainActor () async throws -> Void) {
        if running || closed { return }
        running = true
        Task { @MainActor in
            do { try await action() }
            catch {
                if !closed {
                    status = (cancellation?.cancelled ?? false) || error is CancellationError
                        ? "Reply stopped. Reload history to see the server's saved conversation before sending again."
                        : ConversationContracts.error(error)
                }
            }
            running = false
            if !closed { stopEnabled = false }
        }
    }

    func newChat() { perform { self.reset(); try await self.recommendations() } }
    func reload() { perform { try await self.loadHistory() } }
    func send() { perform { try await self.sendMessage() } }
    func stop() { cancellation?.cancel() }

    func choose(_ id: String?) {
        guard let id, !running else { return }
        selectedHistory = id
        perform { try await self.loadConversation(id) }
    }

    func usePrompt(_ prompt: String) {
        perform { self.input = prompt; try await self.sendMessage() }
    }

    func sendFeedback(_ id: String, positive: Bool) {
        perform {
            if !self.sample, let api = self.api {
                try await api.send("PUT", "/2.2/conversations/feedbacks", .obj(("message_id", id), ("positive", positive)))
            }
            self.status = "Feedback saved."
        }
    }

    func answer(_ id: String, _ permission: JSON, approve: Bool) {
        perform {
            if self.answered.contains(id) { self.status = "This request has already been answered."; return }
            if approve {
                let ok = await WebFlows.ask(Self.permissionText(permission), title: "Approve eero's requested changes?", window: self.window, defaultNo: true)
                if !ok { return }
            }
            if self.sample { self.answered.insert(id); self.status = "Sample decision only."; return }
            self.mcpToken = try await self.token()
            self.answered.insert(id)
            try await self.stream(try ConversationContracts.request(self.networkId, self.conversationId, nil, mcpToken: self.mcpToken,
                                                                   permission: .obj(("approved", approve), ("interrupt_id", id))))
        }
    }

    // MARK: Conversation

    private func reset() {
        conversationId = nil
        entries = []; deltas = [:]; rendered = []; answered = []; feedback = []; widgets = [:]
        waitingForPermission = false
        selectedHistory = nil
    }

    private func loadHistory() async throws {
        if sample { preview(); return }
        guard let api else { return }
        let data = try await api.send("GET", "/2.2/conversations?networkId=" + SignInContracts.escapeData(networkId) + "&excludeEmpty=true")
        if closed { return }
        var items: [HistoryItem] = []
        for row in data["conversations"].list {
            let id = row.s("conversation_id")
            if id.isEmpty { continue }
            items.append(HistoryItem(id: id, label: row.first("description", "created").nilIfEmpty ?? "Previous conversation"))
        }
        history = items
        if let selected = selectedHistory, !items.contains(where: { $0.id == selected }) { selectedHistory = nil }
        status = items.isEmpty ? "No saved conversations were returned." : "Choose a conversation to read its history."
        if let conversationId, !conversationId.isEmpty { try await loadConversation(conversationId) }
    }

    private func loadConversation(_ id: String) async throws {
        guard let api else { return }
        let data = try await api.send("GET", "/2.2/conversations/" + SignInContracts.escapeData(id))
        if closed { return }
        let keep = selectedHistory
        reset()
        selectedHistory = keep
        conversationId = data.s("conversation_id").nilIfEmpty ?? id
        for row in data["message_history"].list {
            let message = row["message"]
            let messageId = row.s("message_id")
            if !message.isNull {
                let user = message.s("sender") == "USER"
                bubble(user ? "You" : "eero", message.s("content"), messageId)
                if !user { addFeedback(messageId) }
            } else if !row["permission_request"].isNull {
                bubble("Previous request", row["permission_request"].first("friendly_sentence", "content"), nil)
            } else if !row["permission_grant"].isNull {
                bubble("Previous decision", row.b("permission_grant", "approved") ? "Approved" : "Declined", nil)
            } else if !row["widget_event"].isNull {
                widget(row["widget_event"], active: false)
            }
        }
        status = "Conversation loaded. You can continue below."
        scrollTick += 1
    }

    private func recommendations() async throws {
        if sample { return }
        guard let api else { return }
        let data = try await api.send("GET", "/2.2/conversations/recommended?networkId=" + SignInContracts.escapeData(networkId))
        if closed { return }
        for row in data["recommendations"].list {
            let prompt = row.s("suggested_prompt")
            if prompt.isEmpty { continue }
            entries.append(ChatEntry(kind: .prompt(label: row.first("title", "cta_text").nilIfEmpty ?? prompt, prompt: prompt)))
        }
    }

    /// Conversation tokens stay in memory and are refreshed for each submitted turn.
    private func token() async throws -> String? {
        guard let api else { return nil }
        do { return try await api.send("POST", "/2.2/conversations/token", .obj(("refresh_token", ""))).s("access_token").nilIfEmpty }
        catch let e as ApiError { if e.sessionExpired { throw e }; return nil }
    }

    private func sendMessage() async throws {
        let message = input.trimmingCharacters(in: .whitespacesAndNewlines)
        _ = try ConversationContracts.request(networkId, conversationId, message)
        if sample {
            bubble("You", message, nil); input = ""
            bubble("eero", "This is a local sample. Sign in to send messages to eero.", nil)
            return
        }
        mcpToken = try await token()
        if closed { return }
        bubble("You", message, nil); input = ""
        try await stream(try ConversationContracts.request(networkId, conversationId, message, mcpToken: mcpToken))
    }

    private func stream(_ body: JSON) async throws {
        if sample { return }
        guard let api else { return }
        deltas["stream-reply"] = nil
        let source = StreamSource()
        waitingForPermission = false
        cancellation = source
        stopEnabled = true
        status = "eero is replying…"
        let client = ConversationClient(api: api)
        let work = Task { @MainActor in
            try await client.stream(body) { value in try await self.deliver(value) }
        }
        source.task = work
        let limit = Task { @MainActor in
            do { try await Task.sleep(nanoseconds: 180 * 1_000_000_000); source.cancel() } catch {}
        }
        defer {
            limit.cancel()
            cancellation = nil
            if !closed { stopEnabled = false }
        }
        do {
            try await work.value
            if !closed { status = "Reply finished." }
        } catch {
            if !source.cancelled { throw error }
            if !closed {
                status = waitingForPermission ? "eero is waiting for your decision. Review the request above." : "Reply stopped. Reload history before sending again."
            }
        }
    }

    private func deliver(_ value: JSON) throws {
        if closed { return }
        try receive(value)
    }

    @discardableResult
    private func bubble(_ sender: String, _ content: String, _ id: String?) -> UUID {
        let entry = ChatEntry(kind: .bubble(sender: sender, text: content))
        entries.append(entry)
        if let id, !id.isEmpty { deltas[id] = entry.id }
        scrollTick += 1
        return entry.id
    }

    private func setBubbleText(_ entryId: UUID, _ update: (String) -> String) {
        guard let i = entries.firstIndex(where: { $0.id == entryId }), case .bubble(let sender, let text) = entries[i].kind else { return }
        entries[i].kind = .bubble(sender: sender, text: update(text))
    }

    private func receive(_ value: JSON) throws {
        if !value.s("conversation_id").isEmpty { conversationId = value.s("conversation_id") }
        let type = value.s("type"), id = value.s("message_id")
        if type == "Error" { throw EeroError.operation("eero could not finish this reply. Reload history before trying again.") }
        if type == "InitialMessage" || type == "MessageDelta" {
            let key = id.isEmpty ? "stream-reply" : id
            let target = deltas[key].flatMap { k in entries.contains(where: { $0.id == k }) ? k : nil } ?? bubble("eero", "", key)
            let content = value.s("content")
            setBubbleText(target) { type == "InitialMessage" ? content : $0 + content }
            if value.b("finished") { addFeedback(id) }
            scrollTick += 1
        }
        if type == "ToolUse" || type == "Reasoning" { status = "eero is checking your request…" }
        if !value["permission_request"].isNull {
            permission(value["permission_request"])
            waitingForPermission = true
            cancellation?.cancel()
        }
        if !value["widget_event"].isNull { widget(value["widget_event"], active: true) }
    }

    private func addFeedback(_ id: String) {
        if id.isEmpty || feedback.contains(id) { return }
        feedback.insert(id)
        entries.append(ChatEntry(kind: .feedback(messageId: id)))
    }

    static func permissionText(_ permission: JSON) -> String {
        permission.s("friendly_sentence") + "\n" + permission["tool_descriptions"].list.map(\.string).joined(separator: "\n")
    }

    private func permission(_ permission: JSON) {
        let id = permission.s("interrupt_id")
        if id.isEmpty || rendered.contains("permission:" + id) { return }
        rendered.insert("permission:" + id)
        bubble("Permission required", Self.permissionText(permission), nil)
        entries.append(ChatEntry(kind: .permission(id: id, permission: permission)))
    }

    private func widget(_ widget: JSON, active: Bool) {
        let id = widget.s("instance_id"), action = widget.s("action").lowercased()
        if let previous = widgets.removeValue(forKey: id) { entries.removeAll { $0.id == previous } }
        if action == "remove" || action == "delete" { return }
        let entry = ChatEntry(kind: .widget(widget, active: active))
        entries.append(entry)
        widgets[id] = entry.id
        scrollTick += 1
    }

    /// Local sample conversation (port of `Preview`).
    func preview() {
        reset()
        bubble("You", "Check my connectivity", nil)
        bubble("eero", "Your sample network is online. The gateway and two wireless eeros are connected.", "sample-reply")
        addFeedback("sample-reply")
        permission(.obj(("interrupt_id", "sample-permission"), ("friendly_sentence", "May I run a connection diagnostic?"),
                        ("tool_descriptions", JSON.array([.string("Check internet health on the selected network.")]))))
        status = "Sample conversation · No account requests or changes."
    }

    /// Field label (port of `MainWindow.Human`).
    static func human(_ key: String) -> String {
        let special = ["ip": "IP address", "mac": "MAC address", "ssid": "Wifi name", "up_mbps": "Upload (Mbps)", "down_mbps": "Download (Mbps)", "ipv6_upstream": "IPv6", "led_on": "Status light", "sqm": "Optimize for conferencing and gaming"]
        if let s = special[key] { return s }
        let spaced = key.replacingOccurrences(of: "_", with: " ").replacingOccurrences(of: ".", with: " ")
            .replacingOccurrences(of: "([a-z])([A-Z])", with: "$1 $2", options: .regularExpression)
        return spaced.split(separator: " ", omittingEmptySubsequences: false).map { word -> String in
            if word.allSatisfy({ $0.isUppercase }) { return String(word) }
            return word.prefix(1).uppercased() + word.dropFirst().lowercased()
        }.joined(separator: " ")
    }
}

// MARK: - Views

struct ConversationView: View {
    @ObservedObject var controller: ConversationController
    @ViewFocus private var inputFocused: Bool

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            header
            transcript
            footer
        }
        .padding(22)
        .frame(minWidth: 700, minHeight: 620)
        .onAppear { controller.start(); inputFocused = true }
        .onChange(of: controller.running) { _, running in if !running { inputFocused = true } }
    }

    private var header: some View {
        VStack(alignment: .leading, spacing: 6) {
            Text("Chat with eero").font(.system(size: 27, weight: .semibold))
            Text(controller.subtitle).font(.system(size: 13)).foregroundStyle(.secondary)
            HStack {
                Button("New chat") { controller.newChat() }
                Button("Reload history") { controller.reload() }
            }
            .disabled(controller.running)
            .padding(.vertical, 7)
            Picker("History", selection: Binding(get: { controller.selectedHistory }, set: { controller.choose($0) })) {
                Text("Choose a previous conversation").tag(String?.none)
                ForEach(controller.history) { Text($0.label).tag(Optional($0.id)) }
            }
            .labelsHidden()
            .frame(minWidth: 260, maxWidth: .infinity)
            .disabled(controller.running)
        }
    }

    private var transcript: some View {
        ScrollViewReader { proxy in
            ScrollView {
                LazyVStack(alignment: .leading, spacing: 12) {
                    ForEach(controller.entries) { entry in
                        ChatEntryView(entry: entry, controller: controller).id(entry.id)
                    }
                    Color.clear.frame(height: 1).id("end")
                }
                .padding(.vertical, 15)
            }
            .onChange(of: controller.scrollTick) { _, _ in
                withAnimation(.easeOut(duration: 0.15)) { proxy.scrollTo("end", anchor: .bottom) }
            }
        }
    }

    private var footer: some View {
        VStack(alignment: .leading, spacing: 6) {
            TextEditor(text: Binding(get: { controller.input }, set: { controller.input = String($0.prefix(8000)) }))
                .font(.system(size: 14))
                .frame(minHeight: 76, maxHeight: 180)
                .overlay(RoundedRectangle(cornerRadius: 6).stroke(Color.secondary.opacity(0.35)))
                .disabled(controller.running)
                .focused($inputFocused)
            HStack {
                Button("Send · ⌘↩") { controller.send() }
                    .keyboardShortcut(.return, modifiers: .command)
                    .disabled(controller.running)
                Button("Stop reply") { controller.stop() }
                    .disabled(!controller.stopEnabled)
            }
            .padding(.vertical, 7)
            Text(controller.status).font(.system(size: 13)).foregroundStyle(.secondary).fixedSize(horizontal: false, vertical: true)
        }
    }
}

private struct ChatEntryView: View {
    let entry: ChatEntry
    @ObservedObject var controller: ConversationController

    var body: some View {
        switch entry.kind {
        case .bubble(let sender, let text):
            VStack(alignment: .leading, spacing: 4) {
                Text(sender).font(.system(size: 13, weight: .semibold)).foregroundStyle(.secondary)
                Text(text).font(.system(size: 15)).textSelection(.enabled).fixedSize(horizontal: false, vertical: true)
            }
            .padding(18)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(RoundedRectangle(cornerRadius: 8).fill(sender == "You" ? Color.accentColor.opacity(0.14) : Color(nsColor: .controlBackgroundColor)))
        case .prompt(let label, let prompt):
            Button(label) { controller.usePrompt(prompt) }
        case .feedback(let id):
            HStack {
                Button("Helpful") { controller.sendFeedback(id, positive: true) }
                Button("Not helpful") { controller.sendFeedback(id, positive: false) }
            }
        case .permission(let id, let permission):
            HStack {
                Button("Decline request") { controller.answer(id, permission, approve: false) }
                Button("Approve request…") { controller.answer(id, permission, approve: true) }
            }
            .disabled(controller.answered.contains(id))
        case .widget(let widget, let active):
            WidgetCard(widget: widget, active: active, controller: controller)
        }
    }
}

private struct WidgetCard: View {
    let widget: JSON
    let active: Bool
    @ObservedObject var controller: ConversationController

    var body: some View {
        let properties = widget["properties"]
        VStack(alignment: .leading, spacing: 6) {
            Text("eero · " + widget.s("widget_type")).font(.system(size: 13, weight: .semibold)).foregroundStyle(.secondary)
            Text(widget.s("content_summary").nilIfEmpty ?? properties.first("prompt_text", "title", "description"))
                .font(.system(size: 15)).fixedSize(horizontal: false, vertical: true)
            ForEach(ConversationController.widgetFields.filter { !properties.s($0).isEmpty }, id: \.self) { field in
                Text(ConversationController.human(field) + ": " + properties.s(field)).font(.system(size: 13)).foregroundStyle(.secondary)
            }
            if active {
                let choices = properties["choices"].list.map(\.string).filter { !$0.isEmpty }
                ForEach(Array(choices.enumerated()), id: \.offset) { _, prompt in
                    Button(prompt) { controller.usePrompt(prompt) }
                }
            }
            let contacts = properties["contacts"].list
            ForEach(Array(contacts.enumerated()), id: \.offset) { _, contact in
                Text(contact.s("title") + ": " + contact.s("content")).font(.system(size: 14)).textSelection(.enabled)
            }
        }
        .padding(18)
        .frame(maxWidth: .infinity, alignment: .leading)
        .background(RoundedRectangle(cornerRadius: 8).fill(Color(nsColor: .controlBackgroundColor)))
        .overlay(RoundedRectangle(cornerRadius: 8).stroke(Color.secondary.opacity(0.2)))
    }
}
